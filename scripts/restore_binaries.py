def sha256(data):
    return hashlib.sha256(data).hexdigest()


def main():
    root = Path(__file__).resolve().parent.parent
    failed = False
    for rel, (digest, blob) in FILES.items():
        data = base64.b64decode(''.join(blob.split()))
        if sha256(data) != digest:
            print(f'{rel}: the embedded data does not match its SHA-256', file=sys.stderr)
            failed = True
            continue
        target = root / rel
        if target.exists() and sha256(target.read_bytes()) == digest:
            print(f'{rel}: already correct')
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
        print(f'{rel}: written, {len(data)} bytes, sha256 {digest[:16]}...')
    return 1 if failed else 0


if __name__ == '__main__':
    sys.exit(main())
