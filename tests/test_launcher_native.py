"""Build and run the native launcher's portable core on this machine (tests/native/test_launcher_core.c).

  cc launcher_core.c test_launcher_core.c -> run

The launcher's container parser, SHA-256 and option parser are the code that decides whether an
installer file is intact, so they are compiled and executed here instead of only being
cross-compiled for Windows. SHA-256 expectations come from Python's hashlib at test time, and the
same binary is then fed installer files built by payload_container.py to check that both parsers
(the C launcher and the Python engine/build script) accept and reject exactly the same bytes.
"""
import hashlib
import shutil
import struct
import subprocess
import tempfile
import unittest
from pathlib import Path

from installer_support import PE_SIZE, fake_pe, fake_sign
from support import ROOT

import payload_container as pc

SOURCE = ROOT / 'app' / 'installer' / 'launcher' / 'launcher_core.c'
TEST = ROOT / 'tests' / 'native' / 'test_launcher_core.c'
LC_OK, LC_NOT_INSTALLER, LC_DAMAGED = 0, 2, 3


def sha_vectors_header():
    """(length, data, expected digest) rows; the data is the first `length` bytes of PATTERN (i % 251)."""
    lengths = [0, 1, 3, 54, 55, 56, 57, 63, 64, 65, 111, 112, 119, 120, 127, 128, 129, 1000, 65536, 1048576]
    rows = [f'    {{{length}, PATTERN, "{hashlib.sha256(bytes(i % 251 for i in range(length))).hexdigest()}"}}'
            for length in lengths]
    return ('/* generated by tests/test_launcher_native.py: (length, data, expected SHA-256 hex digest) */\n'
            '#include <stddef.h>\n'
            '#define PATTERN_SIZE 1048576\nstatic unsigned char PATTERN[PATTERN_SIZE];   /* PATTERN[i] = i % 251, filled in main */\n'
            'static const struct { size_t len; const unsigned char *data; const char *hex; } SHA_VECTORS[] = {\n'
            + ',\n'.join(rows) + '};\n'
            '#define SHA_VECTOR_COUNT (sizeof SHA_VECTORS / sizeof SHA_VECTORS[0])\n')


def compiler():
    for name in ('cc', 'gcc', 'clang'):
        found = shutil.which(name)
        if found:
            return found
    return None


def python_category(error):
    """The C result code a ContainerError corresponds to (payload_container.py's two refusal kinds)."""
    text = str(error)
    return LC_NOT_INSTALLER if 'not a Brave Music Downloader installer' in text or 'too small' in text else LC_DAMAGED


class LauncherCoreTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cc = compiler()
        if not cc:
            raise unittest.SkipTest('no C compiler on this machine (the launcher core is still built by Zig in the release build)')
        cls.folder = Path(tempfile.mkdtemp(prefix='bmd-native-'))
        vectors = cls.folder / 'vectors.h'
        vectors.write_text(sha_vectors_header(), encoding='utf-8')
        cls.exe = cls.folder / 'test_launcher_core'
        build = subprocess.run([cc, '-std=c11', '-Wall', '-Wextra', '-Werror', '-O1', '-fstrict-aliasing',
                                '-I', str(SOURCE.parent), '-include', str(vectors), str(SOURCE), str(TEST),
                                '-o', str(cls.exe)], capture_output=True, text=True)
        if build.returncode != 0:
            shutil.rmtree(cls.folder, ignore_errors=True)
            raise AssertionError('the launcher core must compile without warnings\n' + build.stderr)

    @classmethod
    def tearDownClass(cls):
        shutil.rmtree(cls.folder, ignore_errors=True)

    def codes(self, *files):
        """lc_parse's result code for each file, from the compiled C parser."""
        run = subprocess.run([str(self.exe), '--parse', *map(str, files)], capture_output=True, text=True, timeout=120)
        self.assertEqual(run.returncode, 0, run.stderr)
        self.assertNotIn('open-failed', run.stdout)
        return [int(line) for line in run.stdout.split()]

    def test_the_portable_core_passes_its_native_unit_tests(self):
        run = subprocess.run([str(self.exe)], capture_output=True, text=True, timeout=300)
        self.assertEqual(run.returncode, 0, run.stdout + run.stderr)
        self.assertRegex(run.stdout, r'\b\d+ checks passed')
        print(run.stdout.strip())

    def test_the_c_parser_and_the_python_parser_judge_the_same_files_identically(self):
        import hashlib
        entries = [('Setup.ps1', b'param()\n', True), ('Application.zip', bytes(range(256)) * 40, True),
                   ('ffmpeg', b'\x01\x02\x03' * 5000, False)]
        good = pc.build(fake_pe(), entries)
        parsed = pc.parse(good)
        second = parsed['index_offset'] + pc.ENTRY.size
        pe32 = bytearray(pc.build(fake_pe(magic=0x10B), entries))
        struct.pack_into('<II', pe32, 0x58 + 96 + 4 * 8, len(pe32), 40)

        def refresh(data):
            start, length = parsed['index_offset'], parsed['entry_count'] * pc.ENTRY.size
            data[-32:] = hashlib.sha256(data[start:start + length]).digest()
            return bytes(data)

        def edited(patch):
            data = bytearray(good)
            patch(data)
            return data

        inside = parsed['entries'][2]['offset'] + 10
        odd = pc.build(fake_pe(), entries[:2] + [('ffmpeg', b'\x01\x02\x03' * 5000 + b'!', False)])
        self.assertEqual(len(odd) % 8, 1)
        padded = fake_sign(odd)                                    # the "signing tool" inserts 7 zeros
        spoiled = bytearray(padded)
        spoiled[len(odd)] = 0xFF                                   # inside those zeros
        files = {'unsigned': good, 'signed': fake_sign(good), 'pe32': pc.build(fake_pe(magic=0x10B), entries),
                 'signed-pe32': bytes(pe32) + bytes(40), 'signed-padded': padded, 'padding-flip': bytes(spoiled),
                 'truncated': good[:-1], 'appended-zeros': good + bytes(7), 'appended-eight': good + bytes(8),
                 'appended-byte': good + b'\x01', 'no-header': b'nope' + good[4:],
                 'text': b'random file content' * 50, 'empty': b'', 'executable-only': fake_pe(),
                 'cut-inside-image': good[:PE_SIZE - 4],
                 'index-flip': edited(lambda d: d.__setitem__(parsed['index_offset'] + 5, d[parsed['index_offset'] + 5] ^ 0x5A)),
                 'footer-flip': edited(lambda d: d.__setitem__(len(d) - 40, d[len(d) - 40] ^ 1)),
                 'entry-into-image': refresh(edited(lambda d: struct.pack_into('<Q', d, second + 64, 1))),
                 'entry-past-data': refresh(edited(lambda d: struct.pack_into('<Q', d, second + 72, 2 ** 63 - 1))),
                 'duplicate-name': refresh(edited(lambda d: d.__setitem__(slice(second, second + 64), b'setup.ps1'.ljust(64, b'\0')))),
                 'content-flip': edited(lambda d: d.__setitem__(inside, d[inside] ^ 0xFF))}
        names = list(files)
        paths = []
        for name in names:
            path = self.folder / f'{name}.bin'
            path.write_bytes(files[name])
            paths.append(path)
        c_codes = self.codes(*paths)
        python_codes = []
        for name in names:
            try:
                pc.parse(files[name])
                python_codes.append(LC_OK)
            except pc.ContainerError as exc:
                python_codes.append(python_category(exc))
        self.assertEqual(c_codes, python_codes)
        self.assertEqual(dict(zip(names, c_codes)), {
            'unsigned': LC_OK, 'signed': LC_OK, 'pe32': LC_OK, 'signed-pe32': LC_OK, 'content-flip': LC_OK,
            'signed-padded': LC_OK, 'appended-zeros': LC_OK,
            'truncated': LC_NOT_INSTALLER, 'appended-eight': LC_NOT_INSTALLER, 'no-header': LC_NOT_INSTALLER,
            'text': LC_NOT_INSTALLER, 'empty': LC_NOT_INSTALLER, 'executable-only': LC_NOT_INSTALLER,
            'cut-inside-image': LC_NOT_INSTALLER,
            'index-flip': LC_DAMAGED, 'footer-flip': LC_DAMAGED, 'entry-into-image': LC_DAMAGED,
            'entry-past-data': LC_DAMAGED, 'duplicate-name': LC_DAMAGED, 'appended-byte': LC_DAMAGED,
            'padding-flip': LC_DAMAGED})

    def test_a_container_written_by_the_c_side_is_read_and_verified_by_python(self):
        path = self.folder / 'emitted.exe'
        emit = subprocess.run([str(self.exe), '--emit', str(path)], capture_output=True, text=True, timeout=120)
        self.assertEqual(emit.returncode, 0, emit.stderr)
        parsed = pc.read(path)
        self.assertEqual([(e['name'], e['size'], e['bootstrap']) for e in parsed['entries']],
                         [('Setup.ps1', 4000, True), ('Application.zip', 90000, True),
                          ('python.zip', 3000, True), ('ffmpeg', 1500000, False)])
        target = self.folder / 'ffmpeg.bin'
        digest = pc.copy_entry(path, parsed['entries'][3], target, parsed['entries'][3]['sha256'])
        self.assertEqual((digest, target.stat().st_size), (parsed['entries'][3]['sha256'], 1500000))


if __name__ == '__main__':
    unittest.main()
